import type { AircraftTelemetry } from "../api/types";
import { formatNumber, formatVirtualTime, humanize } from "./format";
import { Empty, Panel, Pill } from "./ui";

function Readout({ label, value, unit }: { label: string; value: string; unit: string }) {
  return (
    <div className="readout">
      <span className="readout__label">{label}</span>
      <span className="readout__value mono">{value}</span>
      <span className="readout__unit">{unit}</span>
    </div>
  );
}

function Compass({ heading }: { heading: number }) {
  return (
    <svg className="compass" viewBox="0 0 100 100" role="img" aria-label={`Heading ${Math.round(heading)} degrees`}>
      <circle cx="50" cy="50" r="44" className="compass__ring" />
      {[0, 90, 180, 270].map((deg) => (
        <text
          key={deg}
          x={50 + 34 * Math.sin((deg * Math.PI) / 180)}
          y={50 - 34 * Math.cos((deg * Math.PI) / 180) + 4}
          className="compass__label"
          textAnchor="middle"
        >
          {["N", "E", "S", "W"][deg / 90]}
        </text>
      ))}
      <g transform={`rotate(${heading} 50 50)`}>
        <path d="M50 14 L57 52 L50 46 L43 52 Z" className="compass__needle" />
      </g>
    </svg>
  );
}

/** Synthetic telemetry exactly as reported by the backend simulator. */
export function TelemetryPanel({ telemetry }: { telemetry: AircraftTelemetry | null | undefined }) {
  return (
    <Panel
      title="Aircraft telemetry"
      subtitle="Synthetic — generated by the scenario simulator"
      actions={telemetry ? <Pill tone="info">{humanize(telemetry.flight_phase)}</Pill> : undefined}
    >
      {telemetry ? (
        <div className="telemetry">
          <div className="telemetry__readouts">
            <Readout label="Altitude" value={formatNumber(telemetry.altitude_ft)} unit="ft" />
            <Readout label="Airspeed" value={formatNumber(telemetry.airspeed_kts)} unit="kts" />
            <Readout label="Heading" value={formatNumber(telemetry.heading_deg).padStart(3, "0")} unit="°" />
          </div>
          <Compass heading={telemetry.heading_deg} />
          <dl className="fields fields--3 telemetry__meta">
            <div className="field">
              <dt className="field__label">Aircraft</dt>
              <dd className="field__value mono">{telemetry.aircraft_id}</dd>
            </div>
            <div className="field">
              <dt className="field__label">Position</dt>
              <dd className="field__value mono">
                {telemetry.latitude.toFixed(3)}, {telemetry.longitude.toFixed(3)}
              </dd>
            </div>
            <div className="field">
              <dt className="field__label">Sim time</dt>
              <dd className="field__value mono">{formatVirtualTime(telemetry.simulation_time)}</dd>
            </div>
          </dl>
          <div className="warnings">
            {telemetry.active_warning_codes.length === 0 ? (
              <span className="meta">No active warning codes</span>
            ) : (
              telemetry.active_warning_codes.map((code) => (
                <Pill key={code} tone="warn">
                  {code}
                </Pill>
              ))
            )}
          </div>
        </div>
      ) : (
        <Empty>No telemetry yet. Start a scenario from the Simulation tab.</Empty>
      )}
    </Panel>
  );
}
